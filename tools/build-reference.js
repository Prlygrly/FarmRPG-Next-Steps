// Builds reference.js (the Reference tab) from the knowledge notes: every game-mechanics note, and the game-data notes
// meant for reading (the snapshot ones that only say how to regenerate a data file are left out).
// Runs from tools/bump-version.js before each push; or by hand: node tools/build-reference.js
const fs = require("fs"), path = require("path");
const root = path.join(__dirname, ".."), dirs = [["mechanics", "How it works"], ["data", "Game data"]];

function readNote(file, group) {
  const text = fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n");
  const m = text.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!m) return null;
  const head = m[1], body = m[2].trim();
  if (/Regenerate with|snapshot-/.test(body)) return null;              // a developer snapshot note
  const field = k => { const f = head.match(new RegExp(`^${k}:\\s*"?(.*?)"?\\s*$`, "m")); return f ? f[1] : ""; };
  // sources: "- id: x" then "resource: ..." and "title: ..."; links only for real URLs
  const sources = {};
  for (const s of head.split(/\n\s*- id:\s*/).slice(1)) {
    const id = s.split("\n")[0].trim(), res = (s.match(/resource:\s*(.*)/) || [])[1] || "", title = ((s.match(/title:\s*"?(.*?)"?\s*$/m) || [])[1] || "").trim();
    sources[id] = { url: /^https?:\/\//.test(res.trim()) ? res.trim().split(/\s/)[0] : null, title };
  }
  return { id: path.basename(file, ".md"), group, title: field("title"), description: field("description"), body, sources };
}

const notes = [];
for (const [dir, group] of dirs)
  for (const f of fs.readdirSync(path.join(root, "knowledge", dir)).filter(f => f.endsWith(".md")).sort()) {
    const n = readNote(path.join(root, "knowledge", dir, f), group);
    if (n) notes.push(n);
  }
const out = `// Generated by tools/build-reference.js from knowledge/. Do not edit by hand.\n(function (root) {\n  root.REFERENCE = ${JSON.stringify(notes)};\n})(typeof window !== "undefined" ? window : globalThis);\n`;
fs.writeFileSync(path.join(root, "reference.js"), out);
console.log(`Reference: ${notes.length} notes`);
